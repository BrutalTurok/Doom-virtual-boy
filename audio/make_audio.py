"""Extract Doom shareware music (MUS, LZSS-compressed) and PC-speaker effects (DP*) into C."""
import sys
sys.path.insert(0, '.')
from wadtool import read_wad, lzss, unlzss
import numpy as np
from scipy.signal import resample_poly
PCM_HZ = 5556
SKIP = {'rifle'}
hdr, L = read_wad(sys.argv[1])
out = open(sys.argv[2], 'w')
out.write('/* Generated by audio/make_audio.py from doom1.wad (shareware v1.9). */\n')
out.write('#include "vb_sound.h"\n\n')
mus = []; pcs = []
for name, d in L:
    if name.startswith('D_'):
        c = lzss(d); assert unlzss(c, len(d)) == d
        cname = 'mus_' + name[2:].lower()
        out.write('static const unsigned char %s[%d] = {%s};\n' % (cname, len(c), ','.join(str(b) for b in c)))
        mus.append((name[2:].lower(), cname, len(d), len(c)))
    elif name.startswith('DS') and name[2:].lower() not in SKIP:
        rate = int.from_bytes(d[2:4], 'little'); n = int.from_bytes(d[4:8], 'little')
        x = np.frombuffer(d[8 + 16:8 + n - 16], dtype=np.uint8).astype(np.float64) - 128.0   # DMX pads 16 bytes each end
        y = resample_poly(x, PCM_HZ, rate)
        # trim trailing near-silence
        nz = np.nonzero(np.abs(y) > 2.0)[0]
        if len(nz): y = y[:nz[-1] + 1]
        peak = np.abs(y).max() or 1.0
        q = np.clip(np.round(y / peak * 7.4), -8, 7).astype(int)
        if len(q) % 2: q = np.append(q, 0)
        packed = bytes(((q[i] & 15) | ((q[i + 1] & 15) << 4)) for i in range(0, len(q), 2))
        cname = 'pcm_' + name[2:].lower()
        out.write('static const unsigned char %s[%d] = {%s};\n' % (cname, len(packed), ','.join(str(b) for b in packed)))
        pcs.append((name[2:].lower(), cname, len(q)))
out.write('\nconst vbsnd_song_t vbsnd_songs[] = {\n')
for n, c, raw, comp in mus: out.write('  {"%s", %s, %d},\n' % (n, c, raw))
out.write('  {0, 0, 0}\n};\n\nconst vbsnd_pcm_t vbsnd_pcm[] = {\n')
for n, c, ln in pcs: out.write('  {"%s", %s, %d},\n' % (n, c, ln))
out.write('  {0, 0, 0}\n};\n')
print('music', sum(m[3] for m in mus), 'bytes compressed;', 'pcm', sum(p[2] for p in pcs)//2, 'bytes,', len(pcs), 'sfx')
